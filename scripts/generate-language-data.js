const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const grammarPath = path.join(projectRoot, 'syntaxes', 'intouch.tmLanguage.json');
const outputPath = path.join(projectRoot, 'packages', 'core', 'src', 'generatedFunctionCatalog.ts');
const grammar = JSON.parse(fs.readFileSync(grammarPath, 'utf8'));

function namesFromPattern(pattern) {
  const expression = pattern.match;
  if (typeof expression !== 'string') {
    return [];
  }
  const start = expression.indexOf('\\b(');
  const end = start < 0 ? -1 : expression.indexOf(')\\b', start + 3);
  if (start < 0 || end < 0) {
    return [];
  }
  return expression.slice(start + 3, end).split('|').filter(name => /^[A-Za-z_$#][A-Za-z0-9_$#-]*$/.test(name));
}

const rows = new Map();
for (const [repositoryName, repository] of Object.entries(grammar.repository ?? {})) {
  for (const pattern of repository.patterns ?? []) {
    const sourceComment = typeof pattern.comment === 'string' ? pattern.comment : '';
    const isFunction = /function/i.test(pattern.name ?? '') || /function/i.test(sourceComment)
      || repositoryName === 'HermesKeywords';
    if (!isFunction) {
      continue;
    }
    const category = repositoryName === 'HermesKeywords' ? 'Hermes helper' : sourceComment || 'InTouch function';
    for (const name of namesFromPattern(pattern)) {
      const key = name.toUpperCase();
      if (!rows.has(key)) {
        rows.set(key, { name, category, sourceComment });
      }
    }
  }
}

const functions = [...rows.values()].sort((left, right) => left.name.localeCompare(right.name, 'en', { sensitivity: 'base' }));
const generated = [
  '// Generated from syntaxes/intouch.tmLanguage.json by scripts/generate-language-data.js.',
  '// Do not edit this file manually.',
  '',
  "export interface KnownFunction {",
  "\tname: string;",
  "\tcategory: string;",
  "\tsourceComment: string;",
  "}",
  '',
  `export const KNOWN_FUNCTIONS: readonly KnownFunction[] = ${JSON.stringify(functions, null, '\t')} as const;`,
  '',
].join('\n');

if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== generated) {
  fs.writeFileSync(outputPath, generated, 'utf8');
}
